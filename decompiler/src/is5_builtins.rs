pub fn name(id: u16) -> Option<&'static str> {
    BUILTINS
        .binary_search_by_key(&id, |&(op, ..)| op)
        .ok()
        .map(|i| BUILTINS[i].1)
}

/// Whether argument `i` of built-in `name` must be a variable.
pub fn is_output(name: &str, i: usize) -> bool {
    match name {
        // The check box of each text/check pair after two fixed arguments.
        "AskOptions" => i >= 3 && i % 2 == 1,
        "Sprintf" => i == 0,
        _ => BUILTINS
            .iter()
            .find(|&&(_, n, _)| n == name)
            .is_some_and(|&(.., mask)| i < 32 && mask & (1 << i) != 0),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_named() {
        assert!(BUILTINS.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(name(0x2a), Some("MessageBox"));
        assert_eq!(name(0x23), Some("StrCompare"));
    }

    #[test]
    fn outputs_follow_the_documented_names() {
        // SilentReadData(szSection, szValName, nValType, svVal, nvVal)
        assert!(!is_output("SilentReadData", 2));
        assert!(is_output("SilentReadData", 3) && is_output("SilentReadData", 4));
        // AskOptions(nValue, szMsg, szText1, nvCheck1, szText2, nvCheck2, ...)
        assert!(!is_output("AskOptions", 2) && is_output("AskOptions", 3));
        assert!(!is_output("AskOptions", 8) && is_output("AskOptions", 9));
        assert!(!is_output("MessageBox", 0) && !is_output("MessageBox", 1));
    }
}
